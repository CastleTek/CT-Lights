	function validateSegmentLayout(segments, ledCount, maximumSegments = null, allowOverlap = false) {
		const count = integer(ledCount);
		const limit = maximumSegments == null ? null : integer(maximumSegments);
		if (count == null || count < 1) return { ok: false, error: "LED count is unavailable; refresh before editing the layout." };
		if (maximumSegments != null && (limit == null || limit < 1)) {
			return { ok: false, error: "The controller's segment limit is unavailable; refresh before editing the layout." };
		}
		if (!Array.isArray(segments)) return { ok: false, error: "The controller returned an invalid segment layout." };

		const ids = new Set();
		const ranges = [];
		for (const segment of segments) {
			const start = integer(segment?.start);
			const stop = integer(segment?.stop);
			if (start != null && stop != null && stop <= start) continue;
			const id = integer(segment?.id);
			if (id == null || id < 0 || (limit != null && id >= limit)) {
				return { ok: false, error: "Every active segment must have a valid explicit ID." };
			}
			if (ids.has(id)) return { ok: false, error: `Segment ${id + 1} appears more than once in the controller layout.` };
			if (start == null || stop == null || start < 0 || stop <= start || stop > count) {
				return { ok: false, error: `Segment ${id + 1} has an invalid LED range.` };
			}
			ids.add(id);
			ranges.push({ id, start, stop, segment });
		}

		ranges.sort((left, right) => left.start - right.start || left.stop - right.stop || left.id - right.id);
		for (let index = 1; !allowOverlap && index < ranges.length; index++) {
			const previous = ranges[index - 1];
			const current = ranges[index];
			if (previous.stop <= current.start) continue;
			const overlapStart = Math.max(previous.start, current.start) + 1;
			const overlapEnd = Math.min(previous.stop, current.stop);
			return {
				ok: false,
				rangeError: true,
				error: `LEDs ${overlapStart}–${overlapEnd} overlap Segments ${previous.id + 1} and ${current.id + 1}. Choose non-overlapping ranges.`
			};
		}
		return { ok: true, count, limit, ranges };
	}

	function newSegmentPlan(segments, ledCount, maximumSegments) {
		const layout = validateSegmentLayout(segments, ledCount, maximumSegments);
		if (!layout.ok) return layout;
		const used = new Set(layout.ranges.map(range => range.id));
		let id = null;
		for (let candidate = 0; candidate < layout.limit; candidate++) {
			if (!used.has(candidate)) {
				id = candidate;
				break;
			}
		}
		if (id == null) return { ok: false, error: "All supported segment slots are already in use." };

		const blankDraft = (start, stop, source = null) => {
			const length = stop - start;
			const sourceOffset = Math.max(0, integer(source?.of) ?? 0);
			return {
				id,
				name: "",
				start: start + 1,
				end: stop,
				grouping: integer(source?.grp) ?? 1,
				spacing: integer(source?.spc) ?? 0,
				offset: Math.min(sourceOffset, Math.max(0, length - 1))
			};
		};

		let cursor = 0;
		for (const range of layout.ranges) {
			if (range.start > cursor) return { ok: true, mode: "gap", draft: blankDraft(cursor, range.start) };
			cursor = Math.max(cursor, range.stop);
		}
		if (cursor < layout.count) return { ok: true, mode: "gap", draft: blankDraft(cursor, layout.count) };
		if (!layout.ranges.length) return { ok: true, mode: "gap", draft: blankDraft(0, layout.count) };

		const splittable = layout.ranges.filter(range => range.stop - range.start >= 2)
			.sort((left, right) => (right.stop - right.start) - (left.stop - left.start)
				|| left.start - right.start || left.id - right.id);
		if (!splittable.length) {
			return { ok: false, error: "No segment contains at least two LEDs to split." };
		}
		const source = splittable[0];
		const split = source.start + Math.ceil((source.stop - source.start) / 2);
		return {
			ok: true,
			mode: "split",
			draft: blankDraft(split, source.stop, source.segment),
			source: { id: source.id, start: source.start, stop: source.stop, frz: Boolean(source.segment.frz) }
		};
	}

