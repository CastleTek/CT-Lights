	function newSegmentBatchPlan(segments, ledCount, maximumSegments, targetSegments = 2) {
		const layout = validateSegmentLayout(segments, ledCount, maximumSegments);
		if (!layout.ok) return layout;
		if (layout.ranges.length !== 1 || layout.ranges[0].id !== 0
			|| layout.ranges[0].start !== 0 || layout.ranges[0].stop !== layout.count) {
			return {
				ok: false,
				error: "Batch creation is available only when Segment 1 is the single full-strip segment."
			};
		}
		const snapshots = validateSegmentAppearanceSnapshots(layout);
		if (!snapshots.ok) return snapshots;
		const count = integer(targetSegments);
		const maximumTargetSegments = Math.min(layout.limit, layout.count);
		if (count == null || count < 2) {
			return { ok: false, error: "A batch must contain at least two segments." };
		}
		if (count > maximumTargetSegments) {
			return {
				ok: false,
				error: `This controller can divide the strip into at most ${maximumTargetSegments} segments.`
			};
		}

		const source = layout.ranges[0].segment;
		const baseLength = Math.floor(layout.count / count);
		const remainder = layout.count % count;
		let start = 0;
		const drafts = Array.from({ length: count }, (_, id) => {
			const length = baseLength + (id < remainder ? 1 : 0);
			const stop = start + length;
			const draft = {
				id,
				name: id === 0 && typeof source.n === "string" ? source.n : "",
				start: start + 1,
				end: stop,
				grouping: integer(source.grp),
				spacing: integer(source.spc),
				offset: Math.min(Math.max(0, integer(source.of) ?? 0), length - 1)
			};
			start = stop;
			return draft;
		});
		return {
			ok: true,
			mode: "batch-split",
			targetSegments: count,
			maximumTargetSegments,
			drafts,
			source: segmentBatchSourceSnapshot(source)
		};
	}

	function buildCreateSegmentBatchMutation(drafts, creationPlan, segments, ledCount, maximumSegments) {
		const layout = validateSegmentLayout(segments, ledCount, maximumSegments);
		if (!layout.ok) return layout;
		const snapshots = validateSegmentAppearanceSnapshots(layout);
		if (!snapshots.ok) return snapshots;
		if (!creationPlan?.ok || creationPlan.mode !== "batch-split"
			|| !Array.isArray(creationPlan.drafts) || !creationPlan.source) {
			return { ok: false, error: "The segment batch proposal is unavailable. Cancel and start again." };
		}
		if (layout.ranges.length !== 1 || layout.ranges[0].id !== 0
			|| layout.ranges[0].start !== 0 || layout.ranges[0].stop !== layout.count) {
			return { ok: false, error: "The segment layout changed. Cancel and start again." };
		}
		const freshSourceSnapshot = segmentBatchSourceSnapshot(layout.ranges[0].segment);
		if (!freshSourceSnapshot
			|| JSON.stringify(freshSourceSnapshot) !== JSON.stringify(creationPlan.source)) {
			return { ok: false, error: "Segment 1 changed. Cancel and start again." };
		}

		const count = integer(creationPlan.targetSegments);
		const maximumTargetSegments = Math.min(layout.limit, layout.count);
		if (count == null || count < 2 || count > maximumTargetSegments
			|| !Array.isArray(drafts) || drafts.length !== count
			|| creationPlan.drafts.length !== count) {
			return { ok: false, error: "The staged segment count is invalid. Cancel and start again." };
		}

		const validated = [];
		const seenIds = new Set();
		for (const draft of drafts) {
			const validation = validateSegmentDraft(draft, ledCount);
			if (!validation.ok) return validation;
			if (seenIds.has(validation.patch.id)) {
				return { ok: false, error: `Segment ${validation.patch.id + 1} appears more than once in the staged layout.` };
			}
			seenIds.add(validation.patch.id);
			validated.push(validation.patch);
		}
		validated.sort((left, right) => left.id - right.id);
		for (let id = 0; id < count; id++) {
			const patch = validated[id];
			if (!patch || patch.id !== id) {
				return { ok: false, error: `The staged layout must contain Segment ${id + 1}.` };
			}
			if (id === 0 ? patch.start !== 0 : patch.start !== validated[id - 1].stop) {
				return {
					ok: false,
					rangeError: true,
					error: "Staged segments must remain adjacent and in physical Segment-number order."
				};
			}
		}
		if (validated[count - 1].stop !== layout.count) {
			return {
				ok: false,
				rangeError: true,
				error: `The staged segments must cover all ${layout.count} LEDs without gaps.`
			};
		}

		const source = layout.ranges[0].segment;
		const sourceName = typeof source.n === "string" ? source.n : "";
		const sourceDraft = drafts.find(draft => integer(draft.id) === 0);
		const patches = validated.map((geometry, id) => {
			if (id === 0) {
				return {
					...geometry,
					// Preserve untouched source bytes; explicit edits use the same name validation as every other draft.
					n: sourceDraft.name === sourceName ? sourceName : geometry.n,
					frz: false
				};
			}
			return { ...geometry, ...segmentAppearancePatch(source), frz: false };
		});
		const mutation = finalizeSegmentMutation("batch-split", segments, patches, ledCount, maximumSegments);
		if (!mutation.ok) return mutation;
		return {
			...mutation,
			targetSegments: count,
			newIds: Array.from({ length: count - 1 }, (_, index) => index + 1)
		};
	}

	function applySegmentGeometryPatches(segments, patches) {
		const byId = new Map();
		for (const segment of segments) {
			const id = integer(segment?.id);
			const start = integer(segment?.start);
			const stop = integer(segment?.stop);
			if (id != null && start != null && stop != null && stop > start) byId.set(id, { ...segment });
		}
		for (const patch of patches) {
			const id = integer(patch?.id);
			if (id == null) continue;
			const existing = byId.get(id) || {};
			const updated = { ...existing, ...patch, id };
			if (Number(updated.stop) > Number(updated.start)) byId.set(id, updated);
			else byId.delete(id);
		}
		return [...byId.values()];
	}

	function finalizeSegmentMutation(mode, segments, patches, ledCount, maximumSegments, newId = null) {
		const prospective = applySegmentGeometryPatches(segments, patches);
		const layout = validateSegmentLayout(prospective, ledCount, maximumSegments);
		if (!layout.ok) return layout;
		const expectedLayout = [];
		for (const range of layout.ranges.slice().sort((left, right) => left.id - right.id)) {
			const validation = validateSegmentDraft(segmentDraft(range.segment), ledCount);
			if (!validation.ok) return { ok: false, error: `Segment ${range.id + 1} has unsupported layout values.` };
			validation.patch.n = typeof range.segment.n === "string" ? range.segment.n : "";
			expectedLayout.push(validation.patch);
		}
		return {
			ok: true,
			mode,
			patches,
			expectedLayout,
			expectedAppearance: layout.ranges.map(range => ({ id: range.id, ...segmentAppearancePatch(range.segment) })),
			expectedSelections: patches.filter(patch => Object.prototype.hasOwnProperty.call(patch, "sel"))
				.map(patch => ({ id: patch.id, selected: Boolean(patch.sel) })),
			newId
		};
	}

	function buildCreateSegmentMutation(draft, creationPlan, segments, ledCount, maximumSegments) {
		const layout = validateSegmentLayout(segments, ledCount, maximumSegments);
		if (!layout.ok) return layout;
		const snapshots = validateSegmentAppearanceSnapshots(layout);
		if (!snapshots.ok) return snapshots;
		const validation = validateSegmentDraft(draft, ledCount);
		if (!validation.ok) return validation;
		if (!creationPlan?.ok || !["gap", "split"].includes(creationPlan.mode)) {
			return { ok: false, error: "The segment proposal is unavailable. Cancel and reopen the editor." };
		}
		if (validation.patch.id !== integer(creationPlan.draft?.id)) {
			return { ok: false, error: "The proposed segment ID changed. Cancel and reopen the editor." };
		}
		if (layout.ranges.some(range => range.id === validation.patch.id)) {
			return { ok: false, error: "That segment slot is already in use. Cancel and reopen the editor." };
		}

		if (creationPlan.mode === "gap") {
			const patch = { ...validation.patch, ...segmentAppearancePatch() };
			return finalizeSegmentMutation("gap", segments, [patch], ledCount, maximumSegments, patch.id);
		}

		const captured = creationPlan.source;
		const sourceRange = layout.ranges.find(range => range.id === integer(captured?.id));
		if (!sourceRange || sourceRange.start !== integer(captured?.start) || sourceRange.stop !== integer(captured?.stop)) {
			return { ok: false, error: "The source segment changed. Cancel and reopen the editor." };
		}
		if (Boolean(sourceRange.segment.frz) !== Boolean(captured?.frz)) {
			return { ok: false, error: "The source segment freeze state changed. Cancel and reopen the editor." };
		}
		const newPatch = validation.patch;
		if (newPatch.start < sourceRange.start || newPatch.stop > sourceRange.stop) {
			return {
				ok: false,
				rangeError: true,
				error: `The new range must stay within Segment ${sourceRange.id + 1} (LEDs ${sourceRange.start + 1}–${sourceRange.stop}).`
			};
		}
		const touchesStart = newPatch.start === sourceRange.start;
		const touchesStop = newPatch.stop === sourceRange.stop;
		if (touchesStart && touchesStop) {
			return { ok: false, rangeError: true, error: "The new segment cannot replace the entire source segment." };
		}
		if (!touchesStart && !touchesStop) {
			return {
				ok: false,
				rangeError: true,
				error: `The new range must reach the first or last LED of Segment ${sourceRange.id + 1}; an interior range would leave two separate remainders.`
			};
		}

		const remainingStart = touchesStart ? newPatch.stop : sourceRange.start;
		const remainingStop = touchesStart ? sourceRange.stop : newPatch.start;
		const sourceDraft = segmentDraft(sourceRange.segment);
		sourceDraft.name = "";
		sourceDraft.start = remainingStart + 1;
		sourceDraft.end = remainingStop;
		sourceDraft.offset = Math.min(Math.max(0, integer(sourceRange.segment.of) ?? 0), remainingStop - remainingStart - 1);
		const sourceValidation = validateSegmentDraft(sourceDraft, ledCount);
		if (!sourceValidation.ok) return { ok: false, error: `The source segment cannot be safely resized: ${sourceValidation.error}` };
		sourceValidation.patch.n = typeof sourceRange.segment.n === "string" ? sourceRange.segment.n : "";
		sourceValidation.patch.frz = false;
		const initializedNewPatch = { ...newPatch, ...segmentAppearancePatch(sourceRange.segment), frz: false };
		return finalizeSegmentMutation("split", segments, [sourceValidation.patch, initializedNewPatch], ledCount, maximumSegments, initializedNewPatch.id);
	}

	function buildEditSegmentMutation(draft, segments, ledCount, maximumSegments) {
		const layout = validateSegmentLayout(segments, ledCount, maximumSegments, true);
		if (!layout.ok) return layout;
		const snapshots = validateSegmentAppearanceSnapshots(layout);
		if (!snapshots.ok) return snapshots;
		const validation = validateSegmentDraft(draft, ledCount);
		if (!validation.ok) return validation;
		if (!layout.ranges.some(range => range.id === validation.patch.id)) {
			return { ok: false, error: "This segment no longer exists. Cancel and reopen the editor." };
		}
		return finalizeSegmentMutation("edit", segments, [validation.patch], ledCount, maximumSegments);
	}

	function segmentAppearanceMatchesPatch(segment, patch) {
		if (!segment || !patch) return false;
		for (const key of ["bri", "cct", "set", "fx", "sx", "ix", "c1", "c2", "c3", "si", "m12", "bm"]) {
			if (Object.prototype.hasOwnProperty.call(patch, key) && Number(segment[key]) !== Number(patch[key])) return false;
		}
		for (const key of ["on", "frz", "sel", "rev", "mi", "o1", "o2", "o3"]) {
			if (Object.prototype.hasOwnProperty.call(patch, key) && Boolean(segment[key]) !== Boolean(patch[key])) return false;
		}
		const capabilities = integer(segment.lc);
		if (capabilities == null || capabilities < 0) return false;
		if ((capabilities & 1) && Object.prototype.hasOwnProperty.call(patch, "pal")
			&& Number(segment.pal) !== Number(patch.pal)) return false;
		if ((capabilities & 3) && Array.isArray(patch.col)) {
			const normalized = colors => Array.from({ length: 3 }, (_, slot) =>
				Array.from({ length: 4 }, (_, channel) => Number(colors?.[slot]?.[channel]) || 0));
			if (JSON.stringify(normalized(segment.col)) !== JSON.stringify(normalized(patch.col))) return false;
		}
		return true;
	}

	function segmentMutationMatchesState(stateOrSegments, mutation, ledCount, maximumSegments) {
		if (!mutation?.ok || !Array.isArray(mutation.expectedLayout)) return false;
		const segments = Array.isArray(stateOrSegments) ? stateOrSegments : stateOrSegments?.seg;
		const layout = validateSegmentLayout(segments, ledCount, maximumSegments);
		if (!layout.ok || layout.ranges.length !== mutation.expectedLayout.length) return false;
		if (!validateSegmentAppearanceSnapshots(layout).ok) return false;
		const actualById = new Map(layout.ranges.map(range => [range.id, range.segment]));
		for (const expected of mutation.expectedLayout) {
			if (!segmentMatchesPatch(actualById.get(expected.id), expected)) return false;
		}
		for (const expected of mutation.expectedAppearance || []) {
			if (!segmentAppearanceMatchesPatch(actualById.get(expected.id), expected)) return false;
		}
		for (const expectation of mutation.expectedSelections || []) {
			if (Boolean(actualById.get(expectation.id)?.sel) !== expectation.selected) return false;
		}
		return true;
	}

	function segmentGeometrySignature(segment, index = 0) {
		const draft = segmentDraft(segment, index);
		return [draft.id, draft.name, draft.start, draft.end, draft.grouping, draft.spacing, draft.offset].join("\u001f");
	}

	function segmentMatchesPatch(segment, patch, index = 0) {
		if (!segment || !patch || segmentId(segment, index) !== Number(patch.id)) return false;
		const name = typeof segment.n === "string" ? segment.n : "";
		return name === String(patch.n ?? "")
			&& Number(segment.start) === Number(patch.start)
			&& Number(segment.stop) === Number(patch.stop)
			&& Number(segment.grp ?? 1) === Number(patch.grp)
			&& Number(segment.spc ?? 0) === Number(patch.spc)
			&& Number(segment.of ?? 0) === Number(patch.of);
	}

	function buildDeleteSegmentUpdate(segments, deleteId, selectedIds, mainSegment) {
		const active = activeSegments(segments);
		const id = integer(deleteId);
		if (id == null || !active.some((segment, index) => segmentId(segment, index) === id)) {
			return { ok: false, error: "That segment is no longer available." };
		}
		if (active.length < 2) return { ok: false, error: "The only active segment cannot be deleted." };

		const remaining = active.filter((segment, index) => segmentId(segment, index) !== id);
		const requested = new Set(Array.from(selectedIds || [], Number).filter(Number.isFinite));
		requested.delete(id);
		const remainingIds = remaining.map((segment, index) => segmentId(segment, index));
		if (!remainingIds.some(remainingId => requested.has(remainingId))) {
			const currentMain = integer(mainSegment);
			requested.add(remainingIds.includes(currentMain) ? currentMain : remainingIds[0]);
		}
		const nextMain = requested.has(integer(mainSegment)) ? integer(mainSegment) : remainingIds.find(remainingId => requested.has(remainingId));
		const selection = remainingIds.map(remainingId => ({ id: remainingId, sel: requested.has(remainingId) }));
		return {
			ok: true,
			remainingIds,
			selectedIds: remainingIds.filter(remainingId => requested.has(remainingId)),
			update: { seg: [{ id, sel: false }, { id, stop: 0 }, ...selection], mainseg: nextMain }
		};
	}

	function deletedSegmentMatchesState(state, deleteId, remainingIds, selectedIds, mainSegment) {
		const id = integer(deleteId);
		const expectedRemaining = Array.from(remainingIds || [], Number);
		const expectedSelected = new Set(Array.from(selectedIds || [], Number));
		const active = activeSegments(state);
		const activeIds = active.map((segment, index) => segmentId(segment, index));
		if (id == null || activeIds.includes(id) || activeIds.length !== expectedRemaining.length) return false;
		if (!expectedRemaining.every(expectedId => activeIds.includes(expectedId))) return false;
		if (Number(state?.mainseg) !== Number(mainSegment)) return false;
		return active.every((segment, index) => Boolean(segment.sel) === expectedSelected.has(segmentId(segment, index)));
	}

	function buildResetSegmentsUpdate(segments, ledCount) {
		const count = integer(ledCount);
		if (count == null || count < 1) return { ok: false, error: "LED count is unavailable; refresh before resetting the layout." };
		const active = activeSegments(segments);
		const first = active.find((segment, index) => segmentId(segment, index) === 0) || active[0] || {};
		const firstName = typeof first.n === "string" ? first.n : "";
		const disable = active
			.map((segment, index) => segmentId(segment, index))
			.filter(id => id !== 0)
			.flatMap(id => [{ id, sel: false }, { id, stop: 0 }]);
		return {
			ok: true,
			update: {
				seg: [{ id: 0, n: firstName, start: 0, stop: count, grp: 1, spc: 0, of: 0, sel: true }, ...disable],
				mainseg: 0
			}
		};
	}

	function resetSegmentsMatchState(state, update) {
		const active = activeSegments(state);
		const expected = update?.seg?.[0];
		const first = active[0];
		return active.length === 1 && segmentId(first, 0) === 0
			&& segmentMatchesPatch(first, expected)
			&& first.sel !== false && Number(state?.mainseg) === Number(update?.mainseg);
	}

	function lowestUnusedPresetId(presets) {
		for (let id = 1; id <= 250; id++) {
			if (!presets || !Object.prototype.hasOwnProperty.call(presets, String(id))) return id;
		}
		return null;
	}

	function validatePresetDraft(draft) {
		const id = integer(draft?.id);
		const name = String(draft?.name ?? "").trim();
		if (id == null || id < 1 || id > 250) return { ok: false, error: "Preset ID must be a whole number from 1 through 250." };
		if (!name) return { ok: false, error: "Enter a preset name." };
		if (utf8Length(name) > 32) return { ok: false, error: "Preset names are limited to 32 UTF-8 bytes." };
		return { ok: true, id, name };
	}

	function buildPresetSaveUpdate(draft, existingPreset = null) {
		const validation = validatePresetDraft(draft);
		if (!validation.ok) return validation;
		const update = {
			psave: validation.id,
			n: validation.name,
			ib: Boolean(draft.includeBrightness),
			sb: Boolean(draft.saveSegmentBounds),
			sc: Boolean(draft.selectedOnly)
		};
		if (draft.useAtStartup) update.bootps = validation.id;
		if (existingPreset && typeof existingPreset.ql === "string" && existingPreset.ql) update.ql = existingPreset.ql;
		return { ok: true, id: validation.id, name: validation.name, update };
	}

	function startupPresetMatchesConfiguration(runtimePreset, persistedPreset, expectedPreset, presets) {
		const expected = integer(expectedPreset);
		return expected != null && expected >= 1 && expected <= 250
			&& startupPresetConfigurationIsUsable(runtimePreset, persistedPreset, presets)
			&& integer(runtimePreset) === expected;
	}

	function startupPresetConfigurationIsConsistent(runtimePreset, persistedPreset) {
		const runtime = integer(runtimePreset);
		const persisted = integer(persistedPreset);
		return runtime != null && runtime >= 0 && runtime <= 250
			&& persisted != null && persisted === runtime;
	}

	function startupPresetConfigurationIsUsable(runtimePreset, persistedPreset, presets) {
		if (!startupPresetConfigurationIsConsistent(runtimePreset, persistedPreset)) return false;
		const runtime = integer(runtimePreset);
		if (runtime === 0) return true;
		if (!presets || typeof presets !== "object" || Array.isArray(presets)
			|| !Object.prototype.hasOwnProperty.call(presets, String(runtime))) return false;
		const preset = presets[String(runtime)];
		return preset != null && typeof preset === "object" && !Array.isArray(preset);
	}

	function presetCaptureSignature(draft, state) {
		const projection = { mainseg: state?.mainseg };
		if (draft?.includeBrightness) {
			for (const key of ["on", "bri", "transition", "bs"]) projection[key] = state?.[key];
		}
		const commonKeys = ["grp", "spc", "of", "on", "frz", "bri", "cct", "set", "lc", "fx", "sx", "ix", "pal", "c1", "c2", "c3", "sel", "rev", "mi", "o1", "o2", "o3", "si", "m12", "bm"];
		projection.seg = activeSegments(state)
			.filter(segment => !draft?.selectedOnly || Boolean(segment.sel))
			.map((segment, index) => {
				const captured = { id: segmentId(segment, index) };
				if (draft?.saveSegmentBounds) {
					for (const key of ["start", "stop", "startY", "stopY"]) {
						if (Object.prototype.hasOwnProperty.call(segment, key)) captured[key] = segment[key];
					}
				}
				captured.n = typeof segment.n === "string" ? segment.n : "";
				captured.col = segment.col;
				for (const key of commonKeys) captured[key] = segment[key];
				for (const key of ["rY", "mY", "tp"]) {
					if (Object.prototype.hasOwnProperty.call(segment, key)) captured[key] = segment[key];
				}
				return captured;
			});
		return JSON.stringify(projection);
	}

	function presetMatchesCurrentState(preset, draft, state, selectedIds, maximumSegments) {
		const validation = validatePresetDraft(draft);
		if (!validation.ok || !preset || typeof preset !== "object") return false;
		const own = (value, key) => Object.prototype.hasOwnProperty.call(value, key);
		const rootKeys = new Set(["n", "ql", "on", "bri", "transition", "bs", "mainseg", "seg"]);
		if (Object.keys(preset).some(key => !rootKeys.has(key))) return false;
		if (!own(preset, "n") || typeof preset.n !== "string" || preset.n !== validation.name) return false;
		if (typeof draft.quickLoad === "string" && draft.quickLoad.length) {
			if (!own(preset, "ql") || typeof preset.ql !== "string" || preset.ql !== String(draft.quickLoad)) return false;
		} else if (own(preset, "ql")) return false;
		if (draft.includeBrightness) {
			if (!own(preset, "on") || typeof preset.on !== "boolean" || preset.on !== state?.on) return false;
			if (!own(preset, "bri") || !Number.isFinite(preset.bri) || preset.bri !== state?.bri) return false;
			for (const key of ["transition", "bs"]) {
				if (!own(state || {}, key) || !own(preset, key) || !Number.isFinite(preset[key]) || preset[key] !== state[key]) return false;
			}
		} else {
			for (const key of ["on", "bri", "transition", "bs"]) {
				if (own(preset, key)) return false;
			}
		}
		if (!own(preset, "mainseg") || !Number.isFinite(preset.mainseg) || preset.mainseg !== state?.mainseg) return false;
		if (!Array.isArray(preset.seg)) return false;
		const selected = new Set(Array.from(selectedIds || [], Number));
		const expected = activeSegments(state).filter((segment, index) => !draft.selectedOnly || selected.has(segmentId(segment, index)));
		if (!expected.length) return false;
		const placeholder = segment => segment && typeof segment === "object" && Object.keys(segment).length === 1
			&& own(segment, "stop") && Number.isFinite(segment.stop) && segment.stop === 0;
		if (draft.selectedOnly && preset.seg.some(placeholder)) return false;
		maximumSegments = integer(maximumSegments);
		if (draft.saveSegmentBounds && !draft.selectedOnly) {
			if (maximumSegments == null || maximumSegments < 1 || preset.seg.length !== maximumSegments) return false;
			const expectedById = new Map(expected.map((segment, index) => [segmentId(segment, index), segment]));
			for (let id = 0; id < maximumSegments; id++) {
				const saved = preset.seg[id];
				if (expectedById.has(id)) {
					if (!saved || segmentId(saved, id) !== id) return false;
				} else if (!placeholder(saved)) return false;
			}
		}
		const savedActive = preset.seg.filter(segment => segment && (segment.stop == null || Number(segment.stop) > Number(segment.start || 0)));
		if (!(draft.saveSegmentBounds && !draft.selectedOnly) && preset.seg.length !== savedActive.length) return false;
		if (savedActive.length !== expected.length) return false;
		const commonKeys = ["grp", "spc", "of", "on", "frz", "bri", "cct", "set", "lc", "fx", "sx", "ix", "pal", "c1", "c2", "c3", "sel", "rev", "mi", "o1", "o2", "o3", "si", "m12", "bm"];
		const booleanKeys = new Set(["on", "frz", "sel", "rev", "mi", "rY", "mY", "tp", "o1", "o2", "o3"]);
		const allowedSegmentKeys = new Set(["id", "start", "stop", "startY", "stopY", "n", "col", ...commonKeys, "rY", "mY", "tp"]);
		return expected.every((segment, index) => {
			const id = segmentId(segment, index);
			const saved = savedActive.find((candidate, savedIndex) => segmentId(candidate, savedIndex) === id);
			if (!saved) return false;
			if (Object.keys(saved).some(key => !allowedSegmentKeys.has(key))) return false;
			if (!own(saved, "id") || !Number.isFinite(saved.id) || saved.id !== id) return false;
			if (draft.saveSegmentBounds) {
				if (!Number.isFinite(saved.start) || !Number.isFinite(saved.stop)
					|| saved.start !== segment.start || saved.stop !== segment.stop) return false;
				for (const key of ["startY", "stopY"]) {
					if (own(segment, key)) {
						if (!own(saved, key) || !Number.isFinite(saved[key]) || saved[key] !== segment[key]) return false;
					} else if (own(saved, key)) return false;
				}
			} else {
				for (const key of ["start", "stop", "startY", "stopY"]) {
					if (own(saved, key)) return false;
				}
			}
			const expectedName = typeof segment.n === "string" ? segment.n : "";
			if (!own(saved, "n") || typeof saved.n !== "string" || saved.n !== expectedName) return false;
			if (!own(segment, "col") || !own(saved, "col") || !Array.isArray(saved.col)
				|| JSON.stringify(saved.col) !== JSON.stringify(segment.col)) return false;
			for (const key of commonKeys) {
				if (!own(segment, key) || !own(saved, key)) return false;
				if (booleanKeys.has(key)) {
					if (typeof saved[key] !== "boolean" || saved[key] !== segment[key]) return false;
				} else if (!Number.isFinite(saved[key]) || saved[key] !== segment[key]) return false;
			}
			for (const key of ["rY", "mY", "tp"]) {
				if (own(segment, key)) {
					if (!own(saved, key) || typeof saved[key] !== "boolean" || saved[key] !== segment[key]) return false;
				} else if (own(saved, key)) return false;
			}
			return true;
		});
	}

	async function verifyReadOnly(readValue, predicate, options = {}) {
		const attempts = Math.max(1, Math.min(12, integer(options.attempts) ?? 7));
		const wait = typeof options.wait === "function"
			? options.wait
			: milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds));
		const delayMilliseconds = Math.max(0, integer(options.delayMilliseconds) ?? 350);
		const initialDelayMilliseconds = Math.max(0, integer(options.initialDelayMilliseconds) ?? 0);
		let value;
		let lastError = null;
		for (let attempt = 0; attempt < attempts; attempt++) {
			if (!attempt && initialDelayMilliseconds) await wait(initialDelayMilliseconds, attempt);
			else if (attempt) await wait(delayMilliseconds, attempt);
			try {
				value = await readValue(attempt);
				lastError = null;
				if (predicate(value)) return { confirmed: true, attempts: attempt + 1, value, lastError: null };
			} catch (error) {
				lastError = error;
			}
		}
		return { confirmed: false, attempts, value, lastError };
	}

