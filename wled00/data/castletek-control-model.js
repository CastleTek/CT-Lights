	function kelvinToRgb(value) {
		const kelvin = Math.max(1000, Math.min(40000, Number(value) || 6550));
		const temperature = kelvin / 100;
		let red;
		let green;
		let blue;
		if (temperature < 66) {
			red = 255;
			const greenTemperature = temperature - 2;
			green = -155.25485562709179 - 0.44596950469579133 * greenTemperature
				+ 104.49216199393888 * Math.log(greenTemperature);
			if (temperature < 20) blue = 0;
			else {
				const blueTemperature = temperature - 10;
				blue = 0.8274096064007395 * blueTemperature - 254.76935184120902
					+ 115.67994401066147 * Math.log(blueTemperature);
			}
		} else {
			const redTemperature = temperature - 55;
			red = 351.97690566805693 + 0.114206453784165 * redTemperature
				- 40.25366309332127 * Math.log(redTemperature);
			const greenTemperature = temperature - 50;
			green = 325.4494125711974 + 0.07943456536662342 * greenTemperature
				- 28.0852963507957 * Math.log(greenTemperature);
			blue = 255;
		}
		return { r: clampColorChannel(Math.floor(red)), g: clampColorChannel(Math.floor(green)), b: clampColorChannel(Math.floor(blue)) };
	}

	function rgbToKelvin(value) {
		const red = clampColorChannel(Array.isArray(value) ? value[0] : value?.r);
		const blue = clampColorChannel(Array.isArray(value) ? value[2] : value?.b);
		if (red === 0 && blue === 0) return 6550;
		const ratio = red === 0 ? Number.POSITIVE_INFINITY : blue / red;
		let lower = 2000;
		let upper = 40000;
		let temperature = 6550;
		while (upper - lower > 0.4) {
			temperature = (upper + lower) / 2;
			const candidate = kelvinToRgb(temperature);
			if (candidate.b / candidate.r >= ratio) upper = temperature;
			else lower = temperature;
		}
		return Math.max(1900, Math.min(10091, Math.round(temperature)));
	}

